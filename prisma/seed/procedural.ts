/** Предметы с генерируемыми (параметрическими) демо-вопросами. */
import { int, multiQ, numQ, q, rng, type Rand, type SeedQuestion, type SeedSubject, type SeedTopic } from "./types";

type Gen = (r: Rand, i: number) => SeedQuestion;

function topic(
  meta: Omit<SeedTopic, "questions">,
  seed: number,
  singles: Gen[],
  multis: (() => SeedQuestion)[],
  singleCount: number,
): SeedTopic {
  const r = rng(seed);
  const questions: SeedQuestion[] = [];
  for (let i = 0; i < singleCount; i++) questions.push(singles[i % singles.length](r, i));
  for (const m of multis) questions.push(multiQ(r, m()));
  return { ...meta, questions };
}

